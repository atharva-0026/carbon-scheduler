"""Load job history for the dashboard, and derive carbon/cost numbers from it.

Reads Postgres if it's reachable and has job rows; otherwise falls back to
the bundled sample CSV (dashboard/sample_data.csv, generated by
scripts/seed_data.py). That fallback is what makes the dashboard demoable
with no running Postgres, Celery worker, Redis, or ElectricityMaps API key.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    # allow `import app.*` when this is run via `streamlit run dashboard/app.py`
    sys.path.insert(0, str(REPO_ROOT))

from app.core.carbon_math import AVG_JOB_POWER_KW, REGION_COST_PER_HOUR  # noqa: E402
from app.core.regions import HOME_REGION  # noqa: E402

SAMPLE_CSV_PATH = Path(__file__).resolve().parent / "sample_data.csv"

JOB_COLUMNS = [
    "id",
    "name",
    "job_type",
    "status",
    "estimated_duration_minutes",
    "deadline",
    "allowed_regions",
    "scheduled_region",
    "scheduled_start",
    "carbon_intensity_actual",
    "carbon_intensity_baseline",
    "created_at",
]

DATETIME_COLUMNS = ["deadline", "scheduled_start", "created_at"]


def _load_from_postgres() -> pd.DataFrame | None:
    try:
        from app.core.db import engine

        df = pd.read_sql(f"SELECT {', '.join(JOB_COLUMNS)} FROM jobs", engine)
    except Exception:
        return None
    return df if not df.empty else None


def _load_from_sample_csv(path: Path = SAMPLE_CSV_PATH) -> pd.DataFrame:
    return pd.read_csv(path)


def load_jobs() -> tuple[pd.DataFrame, str]:
    """Return (jobs dataframe, source label). Source is "postgres" or "sample data"."""
    df = _load_from_postgres()
    source = "postgres"
    if df is None:
        df = _load_from_sample_csv()
        source = "sample data"

    for col in DATETIME_COLUMNS:
        df[col] = pd.to_datetime(df[col], errors="coerce", utc=True)

    return df, source


def with_derived_columns(df: pd.DataFrame) -> pd.DataFrame:
    """Add per-job energy/CO2/cost columns computed from the stored decision.

    A row missing either carbon-intensity reading (still pending, or a
    legacy row from before these columns existed) gets NaN CO2 columns --
    multiplying through NaN propagates automatically, no special-casing
    needed. Cost only depends on (region, duration), so it's still computed
    even when carbon data is missing, except for a NaN/unrecognized region
    (e.g. a "failed" job that never got scheduled), which correctly stays NaN.
    """
    df = df.copy()
    duration_hours = df["estimated_duration_minutes"] / 60.0
    energy_kwh = duration_hours * AVG_JOB_POWER_KW

    df["actual_co2_g"] = df["carbon_intensity_actual"] * energy_kwh
    df["baseline_co2_g"] = df["carbon_intensity_baseline"] * energy_kwh
    df["carbon_saved_g"] = df["baseline_co2_g"] - df["actual_co2_g"]

    home_rate = REGION_COST_PER_HOUR.get(HOME_REGION, 0.0)
    df["actual_cost_usd"] = df["scheduled_region"].map(REGION_COST_PER_HOUR) * duration_hours
    df["baseline_cost_usd"] = home_rate * duration_hours
    df["cost_delta_usd"] = df["actual_cost_usd"] - df["baseline_cost_usd"]

    return df


def summary_metrics(df: pd.DataFrame) -> dict:
    """Headline KPIs for the dashboard's top row. Only counts jobs with both
    carbon-intensity readings (i.e. actually scheduled, not failed/pending)."""
    analyzed = df[df["carbon_saved_g"].notna()]
    total_saved_g = analyzed["carbon_saved_g"].sum()
    total_baseline_g = analyzed["baseline_co2_g"].sum()
    pct_reduction = (total_saved_g / total_baseline_g * 100.0) if total_baseline_g else 0.0
    total_cost_delta = analyzed["cost_delta_usd"].sum()

    return {
        "jobs_analyzed": int(len(analyzed)),
        "jobs_total": int(len(df)),
        "total_carbon_saved_kg": total_saved_g / 1000.0,
        "pct_carbon_reduction": pct_reduction,
        "total_cost_delta_usd": float(total_cost_delta) if pd.notna(total_cost_delta) else 0.0,
    }
